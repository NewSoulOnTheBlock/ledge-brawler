// 14 with its own ring of wall; doors are gaps in two neighbouring rings. rooms.ts proves a map can be crossed.

/** Rooms laid out as they stand, top row first, joined into the rows of one map. */
const join = (rows: string[][][]) => rows.flatMap((row) => row[0].map((_, y) => row.map((room) => room[y]).join("")));
/** A room seen from its other side: what shot or rammed left does it to the right. */
const FLIP: Record<string, string> = { "<": ">", ">": "<", "[": "]", "]": "[" };
const mirror = (room: string[]) => room.map((row) => [...row].reverse().map((ch) => FLIP[ch] ?? ch).join(""));


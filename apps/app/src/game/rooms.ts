/** A stream of numbers from 0 up to 1 that is the same for the same seed. */
export function seeded(seed: number) {
  let s = seed % 2147483647 || 1;
  return () => (s = (s * 16807) % 2147483647) / 2147483647;
}

/** Which rooms of the grid are used, what kind each is, and which of their four sides open. */
interface Plan { w: number; h: number; rooms: ({ kind: Kind; left: boolean; right: boolean; up: boolean; down: boolean; main: boolean; wide?: boolean; drop?: boolean; open?: boolean } | null)[] }

/** A way from the bottom-left room up to the top row, a row at a time, and then rooms hung off its sides. */
export function plan(w: number, h: number, rnd: () => number): Plan {
  const rooms: Plan["rooms"] = Array.from({ length: w * h }, () => null);
  const at = (x: number, y: number) => rooms[y * w + x];
  const open = (x: number, y: number, main = true) => (rooms[y * w + x] ??= { kind: "hall", left: false, right: false, up: false, down: false, main });
  let x = 0, y = h - 1, dir = 1;
  open(x, y).kind = "start";
  for (;;) {
    // Along the row a few rooms, then up; in the top row, to its end. Above the first row the way sometimes goes
    // straight up again, which makes a shaft two rooms tall.
    const far = dir > 0 ? w - 1 : 0, least = y < h - 1 && rnd() < 0.3 ? 0 : 1;
    const run = y === 0 ? Math.abs(far - x) : Math.max(least, Math.min(Math.abs(far - x), Math.floor(rnd() * (w - 1))));
    for (let i = 0; i < run; i++) { open(x, y)[dir > 0 ? "right" : "left"] = true; x += dir; open(x, y)[dir > 0 ? "left" : "right"] = true; }
    if (y === 0) break;
    open(x, y).up = true; y--; open(x, y).down = true;
    dir = x >= w - 1 ? -1 : x <= 0 ? 1 : rnd() < 0.5 ? 1 : -1;
  }
  at(x, y)!.kind = "end";
  // Nooks: an unused room beside a room of the way, joined through their shared wall.
  for (let ry = 0; ry < h; ry++) for (let rx = 0; rx < w; rx++) {
    if (at(rx, ry) || rnd() < 0.12) continue;
    const side = [-1, 1].filter((d) => { const n = rx + d >= 0 && rx + d < w ? at(rx + d, ry) : null; return n?.main && n.kind !== "end"; });
    if (side.length === 0) continue;
    const d = side[Math.floor(rnd() * side.length)];
    Object.assign(open(rx, ry, false), { kind: "nook", [d < 0 ? "left" : "right"]: true });
    at(rx + d, ry)![d < 0 ? "right" : "left"] = true;
  }
  for (const room of rooms) if (room && room.kind === "hall") room.kind = room.up && room.down ? "shaft" : room.up ? "up" : room.down ? "down" : "hall";
  // Some neighbours along the way lose the wall between them and become one chamber; and here and there a room of
  // the way has a hole in its floor over another, a short cut back down.
  for (let ry = 0; ry < h; ry++) for (let rx = 0; rx < w; rx++) {
    const room = at(rx, ry), next = rx + 1 < w ? at(rx + 1, ry) : null, below = ry + 1 < h ? at(rx, ry + 1) : null;
    if (room?.right && next && room.kind !== "start" && next.kind !== "end" && room.kind !== "end" && rnd() < 0.45) room.wide = true;
    if (room?.main && below?.main && !room.down && room.kind === "hall" && below.kind === "hall") { const roll = rnd(); if (roll < 0.25) room.drop = true; else if (roll < 0.6) room.open = true; }
  }
  return { w, h, rooms };
}

/** The cells of a whole level: one character each, as in a room's text. */
export interface Grid { w: number; h: number; cells: string[][] }

/** Lays the plan's rooms out as cells. `pick` chooses which room of a kind to use, for trying one room at a time; left out, chance does. */
export function build(p: Plan, rnd: () => number, pick?: (kind: Kind, of: number) => number): Grid {
  const w = p.w * COLS, h = p.h * ROWS, cells = Array.from({ length: h }, () => Array.from({ length: w }, () => "#"));
  p.rooms.forEach((room, i) => {
    if (!room) return;
    const ox = (i % p.w) * COLS, oy = Math.floor(i / p.w) * ROWS;
    // A start or an end that must also be climbed from or dropped into borrows the shape that allows it.
    const kind: Kind = (room.kind === "start" || room.kind === "end" || room.kind === "nook") && (room.up || room.down) ? (room.up && room.down ? "shaft" : room.up ? "up" : "down") : room.kind;
    const pool = ROOMS[kind], flip = rnd() < 0.5;
    const text = pool[pick ? pick(kind, pool.length) : Math.floor(rnd() * pool.length)].map((row) => (flip ? [...row].reverse().join("") : row));
    const set = (cx: number, cy: number, ch: string) => { cells[oy + cy][ox + cx] = ch; };
    for (let r = 0; r < IN_H; r++) for (let c = 0; c < IN_W; c++) {
      let ch = text[r][c];
      if (kind !== room.kind && "PXBC".includes(ch)) ch = ".";
      set(c + 1, r + 1, ch);
    }
    // Whatever a room's text sets in the air comes to rest on what is under it.
    for (let cy = ROWS - 3; cy >= 1; cy--) for (let cx = 1; cx < COLS - 1; cx++) {
      const ch = cells[oy + cy][ox + cx];
      if (!"PXBCec".includes(ch)) continue;
      let to = cy; while (to + 1 < ROWS - 1 && cells[oy + to + 1][ox + cx] === ".") to++;
      if (to !== cy) { set(cx, cy, "."); set(cx, to, ch); }
    }
    const clear = (cx: number, cy: number) => { if (cells[oy + cy][ox + cx] !== ".") set(cx, cy, "."); };
    // A door: four cells of air at floor height through the ring and two cells in, on a floor that is whole.
    for (const [on, cols] of [[room.left, [0, 1, 2]], [room.right, [COLS - 1, COLS - 2, COLS - 3]]] as const) {
      if (!on) continue;
      for (const cx of cols) { for (let cy = ROWS - 5; cy < ROWS - 1; cy++) clear(cx, cy); set(cx, ROWS - 1, "#"); }
    }
    // A hole in the roof or the floor: four cells wide in the middle, with nothing set in its way.
    if (room.up) for (let cx = 11; cx <= 14; cx++) clear(cx, 0);
    if (room.down || room.drop) for (let cx = 11; cx <= 14; cx++) { clear(cx, ROWS - 1); clear(cx, ROWS - 2); }
    if (room.drop) for (let cx = 11; cx <= 14; cx++) cells[oy + ROWS][ox + cx] = ".";
    // One cavern with the room under it: most of the floor between them goes, and what is left is a line of ledges
    // to cross by. Whatever stood on that floor goes with it.
    if (room.open) for (let cx = 5; cx <= 20; cx++) {
      set(cx, ROWS - 1, (cx - 5) % 5 === 2 || (cx - 5) % 5 === 3 ? "-" : ".");
      cells[oy + ROWS][ox + cx] = ".";
      if (cells[oy + ROWS - 2][ox + cx] !== "#") set(cx, ROWS - 2, ".");
    }
    // One chamber with the room to its right: the wall between them goes, from under the roof to the floor.
    if (room.wide) for (let cy = 2; cy < ROWS - 1; cy++) { clear(COLS - 1, cy); cells[oy + cy][ox + COLS] = "."; }
    // Rock is not laid square. The roof hangs lower in places, the floor rises in others and the walls thicken, away
    // from the doors, the holes and whatever the room's own shape needs kept clear.
    if (kind === "hall" || kind === "down" || kind === "nook") {
      const free = (cx: number, cy: number) => cells[oy + cy][ox + cx] === ".";
      for (let n = 0; n < 4; n++) {
        const from = 3 + Math.floor(rnd() * 17), wide = 2 + Math.floor(rnd() * 4), deep = 1 + Math.floor(rnd() * 3);
        for (let cx = from; cx < Math.min(COLS - 3, from + wide); cx++) for (let cy = 1; cy <= deep; cy++) if ([0, 1, 2, 3, 4].every((d) => free(cx, cy + d))) set(cx, cy, "#"); else break;
      }
      for (let n = 0; n < 2; n++) {
        const from = 4 + Math.floor(rnd() * 15), wide = 2 + Math.floor(rnd() * 3), tall = 1 + Math.floor(rnd() * 2);
        if (room.down || room.drop || room.open) continue;
        for (let cx = from; cx < Math.min(COLS - 4, from + wide); cx++) for (let cy = ROWS - 2; cy > ROWS - 2 - tall; cy--) if ([0, 1, 2, 3, 4].every((d) => free(cx, cy - d)) && cells[oy + cy + 1][ox + cx] === "#") set(cx, cy, "#"); else break;
      }
      for (const cx of [1, COLS - 2]) for (let cy = 1; cy < ROWS - 6; cy++) if (rnd() < 0.5 && free(cx, cy)) set(cx, cy, "#");
    }
    // What a borrowed shape lost: the fighter, the way out, the last enemy or the thing to find, on its floor.
    if (kind !== room.kind) {
      const mark = room.kind === "start" ? "P" : room.kind === "end" ? "X" : "C";
      const spot = [4, 20, 6, 18, 3, 21].find((cx) => cells[oy + ROWS - 2][ox + cx] === "." && cells[oy + ROWS - 3][ox + cx] === "." && cells[oy + ROWS - 1][ox + cx] === "#") ?? 4;
      set(spot, ROWS - 2, mark);
      if (room.kind === "end") set(spot < 12 ? spot + 3 : spot - 3, ROWS - 2, "B");
    }
  });
  return { w, h, cells };
}

const solid = (ch: string | undefined) => ch === undefined || ch === "#";
const floor = (ch: string | undefined) => solid(ch) || ch === "-";
/** Whether a fighter can stand in the cell: air there and above it, something under its feet, and no spikes. */
function stands(g: Grid, x: number, y: number) {
  const at = (cx: number, cy: number) => g.cells[cy]?.[cx];
  const here = at(x, y);
  return !floor(here) && here !== "^" && !floor(at(x, y - 1)) && y - 1 >= 0 && (floor(at(x, y + 1)) || y + 1 >= g.h);
}
/** Whether a fighter's body fits in the cell and the one above: neither rock nor ledge. */
const fits = (g: Grid, x: number, y: number) => x >= 0 && x < g.w && y >= 1 && y < g.h && !floor(g.cells[y][x]) && !floor(g.cells[y - 1][x]);
const wall = (g: Grid, x: number, y: number) => x >= 0 && x < g.w && y >= 0 && y < g.h && solid(g.cells[y][x]);

/** Every cell a fighter can stand in, and the ones it can get to from each by jumping, dashing, wall jumping, or climbing. */
export function moves(g: Grid) {
  const id = (x: number, y: number) => y * g.w + x, out = new Map<number, number[]>();
  const add = (to: number[], cx: number, cy: number) => { if (stands(g, cx, cy)) to.push(id(cx, cy)); };
  const fall = (to: number[], cx: number, fromY: number) => {
    for (let cy = fromY; cy < g.h; cy++) {
      if (!fits(g, cx, cy)) break;
      if (g.cells[cy][cx] === "^") break;
      if (stands(g, cx, cy)) { to.push(id(cx, cy)); break; }
    }
  };
  for (let y = 1; y < g.h; y++) for (let x = 0; x < g.w; x++) {
    if (!stands(g, x, y)) continue;
    const to: number[] = [], rise = g.cells[y][x] === "S" ? 8 : 3;
    // Plain jump: up to `rise` cells up, then across up to 4, then fall.
    for (let up = 0; up <= rise; up++) {
      if (up > 0 && !fits(g, x, y - up)) break;
      for (const dir of [-1, 1]) for (let dx = 1; dx <= 4; dx++) {
        const cx = x + dir * dx;
        if (!fits(g, cx, y - up)) break;
        fall(to, cx, y - up);
      }
    }
    // Wall jump: if a wall is beside us or reachable by jumping into it, kick off it (4 up, 5 across from wall).
    for (const dir of [-1, 1]) {
      // Find a wall within 4 cells horizontally (can jump to it then wall-jump off).
      for (let wx = 1; wx <= 4; wx++) {
        const wallX = x + dir * wx;
        if (wall(g, wallX, y) || wall(g, wallX, y - 1)) {
          // Kick off this wall: 4 up, 5 across in the opposite direction, then fall.
          const kickDir = -dir;
          for (let up = 0; up <= 4; up++) {
            const ky = y - up;
            if (ky < 1) break;
            for (let dx = 1; dx <= 5; dx++) {
              const cx = wallX + kickDir * dx;
              if (!fits(g, cx, ky)) break;
              fall(to, cx, ky);
            }
          }
          break;
        }
        if (!fits(g, wallX, y)) break;
      }
    }
    // Wall climb: infinite — if a wall is within jump reach above, grab it and climb.
    for (const dir of [-1, 1]) {
      let canGrab = false;
      for (let dy = 0; dy <= rise; dy++) {
        if (wall(g, x + dir, y - dy) || wall(g, x + dir, y - dy - 1)) { canGrab = true; break; }
        if (dy > 0 && !fits(g, x, y - dy)) break;
      }
      if (canGrab) {
        for (let up = 1; up < g.h; up++) {
          const cy = y - up;
          if (cy < 1) break;
          if (solid(g.cells[cy][x]) && solid(g.cells[cy - 1]?.[x])) break;
          add(to, x, cy);
          if (fits(g, x, cy)) fall(to, x, cy);
          for (let kx = 1; kx <= 5; kx++) {
            const cx = x - dir * kx;
            if (!fits(g, cx, cy)) break;
            fall(to, cx, cy);
          }
        }
      }
    }
    // Dash: 8 cells horizontal at same height, passing through air.
    for (const dir of [-1, 1]) {
      for (let dx = 1; dx <= 8; dx++) {
        const cx = x + dir * dx;
        if (!fits(g, cx, y)) break;
        add(to, cx, y);
        fall(to, cx, y);
      }
    }
    // Up-dash: straight up, 5 cells.
    for (let up = 1; up <= 5; up++) {
      if (!fits(g, x, y - up)) break;
      add(to, x, y - up);
      for (const dir of [-1, 1]) for (let dx = 1; dx <= 2; dx++) {
        const cx = x + dir * dx;
        if (!fits(g, cx, y - up)) break;
        fall(to, cx, y - up);
      }
    }
    // Diagonal dash: 5 across, 5 up (or down).
    for (const dir of [-1, 1]) {
      for (let d = 1; d <= 5; d++) {
        const cx = x + dir * d, cyUp = y - d, cyDown = y + d;
        if (fits(g, cx, cyUp) && cyUp >= 1) { add(to, cx, cyUp); fall(to, cx, cyUp); }
        if (fits(g, cx, cyDown) && cyDown < g.h) fall(to, cx, cyDown);
        if (!fits(g, cx, cyUp) && !fits(g, cx, cyDown)) break;
      }
    }
    // Dash-jump: 7 across, 4 up (a jump out of a horizontal dash).
    for (const dir of [-1, 1]) {
      for (let up = 0; up <= 4; up++) {
        if (up > 0 && !fits(g, x, y - up)) break;
        for (let dx = 1; dx <= 7; dx++) {
          const cx = x + dir * dx;
          if (!fits(g, cx, y - up)) break;
          fall(to, cx, y - up);
        }
      }
    }
    out.set(id(x, y), to);
  }
  return out;
}

/** What is wrong with a level, if anything: a thing that cannot be got to, or somewhere there is no leaving. */
export function reach(g: Grid): string | null {
  const find = (ch: string) => { const list: number[] = []; g.cells.forEach((row, y) => row.forEach((c, x) => { if (c === ch) list.push(y * g.w + x); })); return list; };
  const [start] = find("P"), [exit] = find("X");
  if (start === undefined || exit === undefined) return "no start or no way out";
  const edges = moves(g), back = new Map<number, number[]>();
  for (const [from, list] of edges) for (const to of list) (back.get(to) ?? back.set(to, []).get(to)!).push(from);
  const flood = (from: number, by: Map<number, number[]>) => { const seen = new Set([from]), todo = [from]; while (todo.length) for (const next of by.get(todo.pop()!) ?? []) if (!seen.has(next)) { seen.add(next); todo.push(next); } return seen; };
  const can = flood(start, edges), home = flood(exit, back);
  if (!can.has(exit)) return "the way out cannot be reached";
  for (const clue of find("C")) if (!can.has(clue)) return "something to find cannot be reached";
  for (const cell of can) if (!home.has(cell)) return `a trap at cell ${cell % g.w}, ${Math.floor(cell / g.w)}`;
  return null;
}


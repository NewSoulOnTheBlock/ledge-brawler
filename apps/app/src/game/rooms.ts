// How a campaign's levels are made: rooms on a grid, joined into one large place with a way through it and
// branches off it. A room is drawn in text, a cell to a character; the rooms a level uses, and the doors between
// them, come from its seed, so a level is the same every time. `reach` proves a level can be crossed: that its way
// out and everything to find in it can be got to on plain jumps, and that nowhere in it is a trap.
